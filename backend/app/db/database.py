import os
from sqlalchemy.ext.asyncio import create_async_engine, AsyncEngine, AsyncSession, async_sessionmaker
from sqlalchemy.orm import DeclarativeBase
from sqlalchemy import text
from sqlalchemy.schema import sort_tables_and_constraints
from app.config import settings

# Extract DB directory and ensure it exists locally if SQLite file path
db_url = settings.DATABASE_URL
if db_url.startswith("sqlite+aiosqlite:///"):
    path = db_url.replace("sqlite+aiosqlite:///", "")
    dir_path = os.path.dirname(path)
    if dir_path:
        try:
            os.makedirs(dir_path, exist_ok=True)
        except OSError:
            pass

def _clean_credential(value):
    if isinstance(value, str):
        return value.strip("\"' \t\r\n")
    return value


def create_database_engine(database_url: str, connect_args=None) -> AsyncEngine:
    """Build an async SQLAlchemy engine for the configured database URL."""
    driver_args = dict(connect_args or {})
    if database_url.startswith("oracle+oracledb://"):
        if settings.ORACLE_USER:
            driver_args.setdefault("user", _clean_credential(settings.ORACLE_USER))
        if settings.ORACLE_PASSWORD:
            driver_args.setdefault("password", _clean_credential(settings.ORACLE_PASSWORD))
        if settings.ORACLE_DSN:
            driver_args.setdefault("dsn", _clean_credential(settings.ORACLE_DSN))
        for key in ("user", "password", "dsn"):
            if key in driver_args and isinstance(driver_args[key], str):
                driver_args[key] = _clean_credential(driver_args[key])
    return create_async_engine(
        database_url,
        connect_args=(
            {"check_same_thread": False} if "sqlite" in database_url else driver_args
        ),
        echo=False,
    )


engine = create_database_engine(db_url)

AsyncSessionLocal = async_sessionmaker(
    bind=engine,
    class_=AsyncSession,
    expire_on_commit=False,
    autocommit=False,
    autoflush=False
)

class Base(DeclarativeBase):
    pass


def get_tables_in_dependency_order():
    """Return mapped tables ordered by foreign keys, omitting cyclic edges."""
    return [
        table
        for table, _constraints in sort_tables_and_constraints(Base.metadata.tables.values())
        if table is not None
    ]


async def sync_oracle_identity_values(session: AsyncSession) -> None:
    """Advance Oracle identity generators after importing explicit primary keys."""
    if session.bind is None or session.bind.dialect.name != "oracle":
        return
    for table in get_tables_in_dependency_order():
        for column in table.columns:
            if column.identity is not None:
                await session.execute(text(
                    f"ALTER TABLE {table.name} MODIFY ({column.name} "
                    "GENERATED BY DEFAULT AS IDENTITY (START WITH LIMIT VALUE))"
                ))

async def get_db():
    async with AsyncSessionLocal() as session:
        try:
            yield session
        finally:
            await session.close()
