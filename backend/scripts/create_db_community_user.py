#!/usr/bin/env python3
"""
Create Dedicated Database Tables and Scoped User for Greenline Community Microservice
Connects using ADMIN/DBA credentials and provisions:
- Dedicated tables (community_posts, community_comments) in the target schema
- Dedicated GREENLINE_COMMUNITY user with:
  - SELECT, INSERT, UPDATE, DELETE strictly on community_posts and community_comments
  - ZERO privileges on all 21 core financial tables
  - Zero DDL privileges (CREATE SESSION only)
  - AFTER LOGON trigger setting CURRENT_SCHEMA
"""

import os
import sys
import argparse
import secrets
import string
import oracledb
from dotenv import load_dotenv

ROOT_DIR = os.path.abspath(os.path.join(os.path.dirname(__file__), "..", ".."))
load_dotenv(os.path.join(ROOT_DIR, ".env"))

COMMUNITY_TABLES = [
    "community_posts",
    "community_comments",
    "community_users",
]

CORE_FINANCIAL_TABLES = [
    "users",
    "accounts",
    "assets",
    "transactions",
    "lots",
    "lot_sales",
    "price_history",
    "dividends",
    "expected_dividends",
    "cash_flows",
    "cashflow_transactions",
    "cashflow_payments",
    "cashflow_items",
    "categories",
    "networth_snapshots",
    "networth_by_asset_class",
    "xirr_cache",
    "benchmarks",
    "app_settings",
    "api_keys",
    "schema_migrations",
]


def generate_secure_oracle_password(length: int = 20) -> str:
    """Generate a password compliant with Oracle Autonomous Database complexity rules."""
    upper = secrets.choice(string.ascii_uppercase)
    lower = secrets.choice(string.ascii_lowercase)
    digit = secrets.choice(string.digits)
    sym = secrets.choice("#_$")
    all_chars = string.ascii_letters + string.digits + "#_$"
    rest = "".join(secrets.choice(all_chars) for _ in range(length - 4))
    return f"{upper}{lower}{digit}{sym}{rest}"


def clean_credential(val: str) -> str:
    if isinstance(val, str):
        return val.strip("\"' \t\r\n")
    return val


def main():
    parser = argparse.ArgumentParser(description="Create dedicated Community tables and scoped user in Oracle DB")
    parser.add_argument("--username", default="GREENLINE_COMMUNITY", help="User name to create (default: GREENLINE_COMMUNITY)")
    parser.add_argument("--password", default=os.getenv("COMMUNITY_DB_PASSWORD", "SecureCommunity2026#DbPass"), help="Password for user")
    parser.add_argument("--schema", default=None, help="Schema containing tables (defaults to ADMIN or GREENLINE_TEST)")
    parser.add_argument("--dsn", default=None, help="Oracle DB connection DSN")
    args = parser.parse_args()

    admin_user = clean_credential(os.getenv("ORACLE_ADMIN_USER", os.getenv("ORACLE_USER", "system")))
    admin_password = clean_credential(os.getenv("ORACLE_ADMIN_PASSWORD", os.getenv("ORACLE_PASSWORD", "test_password")))
    dsn = clean_credential(args.dsn or os.getenv("ORACLE_TEST_DSN", os.getenv("ORACLE_DSN", "localhost:1521/FREEPDB1")))

    user_name = clean_credential(args.username).upper()
    user_password = args.password or generate_secure_oracle_password()

    print(f"[*] Connecting to Oracle Database as {admin_user}...")
    try:
        conn = oracledb.connect(user=admin_user, password=admin_password, dsn=dsn)
    except Exception as e:
        print(f"[Error] Failed to connect to Oracle as {admin_user}: {e}")
        sys.exit(1)

    cursor = conn.cursor()

    try:
        # Detect available permanent tablespace
        cursor.execute("SELECT property_value FROM database_properties WHERE property_name = 'DEFAULT_PERMANENT_TABLESPACE'")
        row = cursor.fetchone()
        default_ts = row[0] if row else "DATA"

        # Detect target schema if not specified
        if args.schema:
            target_schema = clean_credential(args.schema).upper()
        else:
            cursor.execute("SELECT owner FROM all_tables WHERE table_name = 'USERS' AND owner IN ('GREENLINE_TEST', 'ADMIN')")
            row = cursor.fetchone()
            target_schema = row[0] if row else os.getenv("ORACLE_SCHEMA", "ADMIN")

        print(f"[*] Target schema identified as {target_schema}")

        # 1. Ensure dedicated community tables exist in target schema
        cursor.execute("SELECT table_name FROM all_tables WHERE owner = :o AND table_name = 'COMMUNITY_POSTS'", o=target_schema)
        if not cursor.fetchone():
            print(f"[*] Creating {target_schema}.community_posts...")
            cursor.execute(f"""
            CREATE TABLE {target_schema}.community_posts (
                id NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                user_id VARCHAR2(255) NOT NULL,
                author_pseudonym VARCHAR2(255),
                content CLOB NOT NULL,
                media_attachments CLOB,
                comments_count NUMBER DEFAULT 0 NOT NULL,
                created_at TIMESTAMP WITH TIME ZONE DEFAULT CURRENT_TIMESTAMP NOT NULL,
                updated_at TIMESTAMP WITH TIME ZONE DEFAULT CURRENT_TIMESTAMP NOT NULL
            )
            """)

        cursor.execute("SELECT table_name FROM all_tables WHERE owner = :o AND table_name = 'COMMUNITY_COMMENTS'", o=target_schema)
        if not cursor.fetchone():
            print(f"[*] Creating {target_schema}.community_comments...")
            cursor.execute(f"""
            CREATE TABLE {target_schema}.community_comments (
                id NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                post_id NUMBER NOT NULL REFERENCES {target_schema}.community_posts(id) ON DELETE CASCADE,
                parent_comment_id NUMBER REFERENCES {target_schema}.community_comments(id) ON DELETE CASCADE,
                user_id VARCHAR2(255) NOT NULL,
                author_pseudonym VARCHAR2(255),
                content CLOB NOT NULL,
                created_at TIMESTAMP WITH TIME ZONE DEFAULT CURRENT_TIMESTAMP NOT NULL,
                updated_at TIMESTAMP WITH TIME ZONE DEFAULT CURRENT_TIMESTAMP NOT NULL
            )
            """)

        cursor.execute("SELECT table_name FROM all_tables WHERE owner = :o AND table_name = 'COMMUNITY_USERS'", o=target_schema)
        if not cursor.fetchone():
            print(f"[*] Creating {target_schema}.community_users...")
            cursor.execute(f"""
            CREATE TABLE {target_schema}.community_users (
                user_uuid VARCHAR2(36) PRIMARY KEY,
                auth0_sub VARCHAR2(255) NOT NULL UNIQUE,
                pseudonym VARCHAR2(255) NOT NULL,
                created_at TIMESTAMP WITH TIME ZONE DEFAULT CURRENT_TIMESTAMP NOT NULL,
                updated_at TIMESTAMP WITH TIME ZONE DEFAULT CURRENT_TIMESTAMP NOT NULL
            )
            """)

        # 2. Check if user exists; create or alter
        cursor.execute("SELECT username FROM all_users WHERE username = :u", u=user_name)
        exists = cursor.fetchone() is not None

        if exists:
            print(f"[*] User {user_name} already exists. Updating password...")
            try:
                cursor.execute(f'ALTER USER {user_name} IDENTIFIED BY "{user_password}"')
            except oracledb.DatabaseError as dbe:
                (err,) = dbe.args
                if err.code == 28007:  # Password cannot be reused (already identical)
                    print(f"[*] Password for {user_name} is already current.")
                else:
                    raise
        else:
            print(f"[*] Creating user {user_name} with tablespace {default_ts}...")
            cursor.execute(
                f'CREATE USER {user_name} IDENTIFIED BY "{user_password}" '
                f'DEFAULT TABLESPACE {default_ts} TEMPORARY TABLESPACE TEMP QUOTA UNLIMITED ON {default_ts}'
            )

        print(f"[*] Granting CREATE SESSION to {user_name}...")
        cursor.execute(f"GRANT CREATE SESSION TO {user_name}")

        print(f"[*] Granting SELECT, INSERT, UPDATE, DELETE on community tables in {target_schema} to {user_name}...")
        for table in COMMUNITY_TABLES:
            cursor.execute(f"GRANT SELECT, INSERT, UPDATE, DELETE ON {target_schema}.{table} TO {user_name}")

        print(f"[*] Ensuring zero privileges on all {len(CORE_FINANCIAL_TABLES)} core financial tables...")
        for table in CORE_FINANCIAL_TABLES:
            try:
                cursor.execute(f"REVOKE ALL ON {target_schema}.{table} FROM {user_name}")
            except Exception:
                pass

        print(f"[*] Creating AFTER LOGON trigger on {user_name} schema setting CURRENT_SCHEMA = {target_schema}...")
        trigger_sql = f"""
        CREATE OR REPLACE TRIGGER {user_name}.set_current_schema
        AFTER LOGON ON {user_name}.SCHEMA
        BEGIN
          EXECUTE IMMEDIATE 'ALTER SESSION SET CURRENT_SCHEMA = {target_schema}';
        END;
        """
        cursor.execute(trigger_sql)
        conn.commit()
        print(f"[+] Successfully provisioned {user_name} with least-privilege community microservice access.")

    except Exception as e:
        print(f"[Error] Failed to provision community user {user_name}: {e}")
        sys.exit(1)
    finally:
        cursor.close()
        conn.close()


if __name__ == "__main__":
    main()
