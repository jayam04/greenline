def test_create_database_engine_supports_oracle_async_dialect(monkeypatch):
    pytest.importorskip("oracledb")
    from app.config import settings

    monkeypatch.setattr(settings, "ORACLE_USER", "greenline")
    monkeypatch.setattr(settings, "ORACLE_PASSWORD", "secret")
    monkeypatch.setattr(settings, "ORACLE_DSN", "(description=walletless-tls)")
    engine = create_database_engine(
        "oracle+oracledb://@"
    )
    try:
        assert engine.dialect.name == "oracle"
        assert engine.dialect.is_async
    finally:
        # No connection is opened by this test.
        import asyncio
        asyncio.run(engine.dispose())


def test_oracle_schema_script_contains_current_models():
    from pathlib import Path

    sql = Path("backend/app/db/schemas/seed.sql").read_text()
    for table_name in Base.metadata.tables:
        match = re.search(
            rf"CREATE TABLE {re.escape(table_name)} \((.*?)\n\);",
            sql,
            re.IGNORECASE | re.DOTALL,
        )
        assert match, f"Missing table DDL for {table_name}"
        for column in Base.metadata.tables[table_name].columns:
            assert column.name.lower() in match.group(1).lower(), (
                f"Missing {table_name}.{column.name} from Oracle DDL"
            )
        for index in Base.metadata.tables[table_name].indexes:
            assert index.name in sql
    assert "create table schema_migrations" in sql.lower()
    assert '"key" VARCHAR2(255 CHAR)' in sql
    assert "GENERATED BY DEFAULT AS IDENTITY" in sql


@pytest.mark.anyio
async def test_copy_database_preserves_rows_and_rejects_nonempty_target():
    source_engine = create_async_engine("sqlite+aiosqlite:///:memory:")
    target_engine = create_async_engine("sqlite+aiosqlite:///:memory:")
    async with source_engine.begin() as conn:
        await conn.run_sync(Base.metadata.create_all)
    async with target_engine.begin() as conn:
        await conn.run_sync(Base.metadata.create_all)
    SourceSession = async_sessionmaker(source_engine, class_=AsyncSession, expire_on_commit=False)
    TargetSession = async_sessionmaker(target_engine, class_=AsyncSession, expire_on_commit=False)

    async with SourceSession() as source:
        source.add(User(user_id=42, username="oracle-user", password_hash="hash"))
        source.add(Account(account_id=77, account_name="Broker", account_type="demat"))
        source.add(Asset(asset_id=22, symbol="ABC", name="ABC Corp", asset_type="stock"))
        source.add(Transaction(
            transaction_id=91, account_id=77, asset_id=22, transaction_type="buy",
            transaction_date=datetime.date(2024, 1, 2), total_amount=100,
        ))
        await source.commit()

    await copy_database(SourceSession, TargetSession)
    async with TargetSession() as target:
        assert (await target.execute(select(User.user_id))).scalars().all() == [42]
        assert (await target.execute(select(Account.account_id))).scalars().all() == [77]
        tx = (await target.execute(select(Transaction))).scalar_one()
        assert (tx.transaction_id, tx.account_id, tx.asset_id) == (91, 77, 22)
        target.add(User(user_id=99, username="existing", password_hash="hash"))
        await target.commit()

    with pytest.raises(ValueError, match="empty"):
        await copy_database(SourceSession, TargetSession)
    await source_engine.dispose()
    await target_engine.dispose()


@pytest.mark.anyio
async def test_migrations_are_idempotent_on_sqlite():
    engine = create_async_engine("sqlite+aiosqlite:///:memory:")
    Session = async_sessionmaker(engine, class_=AsyncSession, expire_on_commit=False)
    async with Session() as session:
        await run_db_migrations(session)
        await run_db_migrations(session)
        assert (await session.execute(select(User))).scalars().all() == []
    await engine.dispose()


@pytest.mark.anyio
async def test_oracle_logical_backup_round_trips_all_model_tables(tmp_path, monkeypatch):
    from app.config import settings

    source_engine = create_async_engine("sqlite+aiosqlite:///:memory:")
    target_engine = create_async_engine("sqlite+aiosqlite:///:memory:")
    async with source_engine.begin() as conn:
        await conn.run_sync(Base.metadata.create_all)
    async with target_engine.begin() as conn:
        await conn.run_sync(Base.metadata.create_all)
    SourceSession = async_sessionmaker(source_engine, class_=AsyncSession, expire_on_commit=False)
    TargetSession = async_sessionmaker(target_engine, class_=AsyncSession, expire_on_commit=False)
    monkeypatch.setattr(settings, "DATABASE_URL", "oracle+oracledb://db.example.com/greenline")
    monkeypatch.setattr(settings, "BACKUP_DIR", str(tmp_path))

    async with SourceSession() as source:
        source.add(User(user_id=7, username="backup-user", password_hash="hash"))
        source.add(Account(account_id=3, account_name="Backup Broker", account_type="demat"))
        source.add(Asset(asset_id=4, symbol="XYZ", name="XYZ Corp", asset_type="stock"))
        source.add(Transaction(
            transaction_id=5, account_id=3, asset_id=4, transaction_type="buy",
            transaction_date=datetime.date(2023, 6, 1), total_amount=30,
        ))
        await source.commit()
        result = await create_backup(source)
    assert result["filename"].endswith(".json")
    assert json.loads((tmp_path / result["filename"]).read_text())["format"] == "greenline-db-backup-v1"

    async with TargetSession() as target:
        await restore_from_backup(result["filename"], target)
        users = (await target.execute(select(User))).scalars().all()
        assert [(row.user_id, row.username) for row in users] == [(7, "backup-user")]
        restored_transaction = (await target.execute(select(Transaction))).scalar_one()
        assert (restored_transaction.transaction_id, restored_transaction.account_id, restored_transaction.asset_id) == (5, 3, 4)

    await source_engine.dispose()
    await target_engine.dispose()
