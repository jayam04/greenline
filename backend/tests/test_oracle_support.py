def test_oracle_schema_script_contains_current_models():
    from pathlib import Path

    candidates = [
        Path("backend/app/db/schemas/seed.sql"),
        Path("app/db/schemas/seed.sql"),
    ]
    sql_path = next(p for p in candidates if p.exists())
    sql = sql_path.read_text()
    for table_name in Base.metadata.tables:
        match = re.search(
            rf"CREATE TABLE {re.escape(table_name)} \((.*?)\n\);",
            sql,
            re.IGNORECASE | re.DOTALL,
        )
        assert match, f"Missing table DDL for {table_name}"
        for column in Base.metadata.tables[table_name].columns:
            assert column.name.lower() in match.group(1).lower(), (
                f"Missing {table_name}.{column.name} from Oracle DDL"
            )
    assert "create table schema_migrations" in sql.lower()
    assert '"key" VARCHAR2(255 CHAR)' in sql
    assert "GENERATED BY DEFAULT AS IDENTITY" in sql


@pytest.mark.anyio
async def test_migrations_are_idempotent_on_oracle(db_session: AsyncSession):
    await run_db_migrations(db_session)
    await run_db_migrations(db_session)
    result = await db_session.execute(select(User).where(User.user_id == 0))
    assert result.scalars().first() is not None


@pytest.mark.anyio
async def test_migrate_user_rls_handles_foreign_key_children_safely(db_session: AsyncSession):
    # Create user 1 and a child record (ApiKey) referencing user 1
    user1 = User(user_id=1, username="admin_temp", password_hash="hash")
    db_session.add(user1)
    await db_session.flush()

    key = ApiKey(user_id=1, name="CLI Key", key_prefix="gl_1234", key_hash="hash_test_rls", is_active=True)
    db_session.add(key)
    await db_session.commit()

    # Run migration - must safely migrate user 1 to 0 or leave 0 intact
    await _migrate_user_rls(db_session)
    db_session.expire_all()

    # Verify admin user 0 exists
    res = await db_session.execute(select(User).where(User.user_id == 0))
    assert res.scalars().first() is not None


@pytest.mark.anyio
async def test_oracle_logical_backup_round_trips_all_model_tables(tmp_path, monkeypatch, db_session: AsyncSession):
    from app.config import settings

    monkeypatch.setattr(settings, "DATABASE_URL", "oracle+oracledb://db.example.com/greenline")
    monkeypatch.setattr(settings, "BACKUP_DIR", str(tmp_path))

    account = Account(account_name="Backup Broker", broker_name="B", account_type="demat", user_id=0)
    asset = Asset(symbol="XYZ", name="XYZ Corp", asset_type="stock")
    db_session.add_all([account, asset])
    await db_session.flush()

    transaction = Transaction(
        account_id=account.account_id, asset_id=asset.asset_id, transaction_type="buy",
        transaction_date=datetime.date(2023, 6, 1), total_amount=30, user_id=0
    )
    db_session.add(transaction)
    await db_session.commit()

    result = await create_backup(db_session)
    assert result["filename"].endswith(".json")
    backup_file = tmp_path / result["filename"]
    assert json.loads(backup_file.read_text())["format"] == "greenline-db-backup-v1"

    # Verify restore works
    restore_res = await restore_from_backup(result["filename"], db_session)
    assert restore_res["status"] == "success"
