from sqlalchemy.ext.asyncio import create_async_engine, AsyncEngine, AsyncSession, async_sessionmaker
from sqlalchemy.orm import DeclarativeBase
from sqlalchemy import event, text
from sqlalchemy.schema import sort_tables_and_constraints
try:
    from ..config import settings
except (ImportError, ValueError):
    from app.config import settings

db_url = settings.DATABASE_URL


def _clean_credential(value):
    if isinstance(value, str):
        return value.strip("\"' \t\r\n")
    return value


def create_database_engine(database_url: str, connect_args=None, **kwargs) -> AsyncEngine:
    """Build an async SQLAlchemy engine for Oracle Database."""
    driver_args = dict(connect_args or {})
    engine_kwargs = {"echo": False}
    engine_kwargs.update(kwargs)
    if database_url.startswith("oracle+oracledb://"):
        if settings.ORACLE_USER:
            driver_args.setdefault("user", _clean_credential(settings.ORACLE_USER))
        if settings.ORACLE_PASSWORD:
            driver_args.setdefault("password", _clean_credential(settings.ORACLE_PASSWORD))
        if settings.ORACLE_DSN:
            driver_args.setdefault("dsn", _clean_credential(settings.ORACLE_DSN))
        driver_args.setdefault("stmtcachesize", 50)
        for key in ("user", "password", "dsn"):
            if key in driver_args and isinstance(driver_args[key], str):
                driver_args[key] = _clean_credential(driver_args[key])

        poolclass = engine_kwargs.get("poolclass")
        is_null_pool = poolclass is not None and (
            getattr(poolclass, "__name__", "") == "NullPool" or str(poolclass) == "<class 'sqlalchemy.pool.impl.NullPool'>"
        )
        if not is_null_pool:
            engine_kwargs.setdefault("pool_size", 10)
            engine_kwargs.setdefault("max_overflow", 20)
        else:
            engine_kwargs.pop("pool_size", None)
            engine_kwargs.pop("max_overflow", None)

        engine_kwargs.setdefault("pool_recycle", 1800)
        engine_kwargs.setdefault("pool_pre_ping", True)
    return create_async_engine(
        database_url,
        connect_args=driver_args,
        **engine_kwargs
    )


engine = create_database_engine(db_url)

if db_url.startswith("oracle+oracledb://") and getattr(settings, "ORACLE_SCHEMA", None):
    target_schema = _clean_credential(settings.ORACLE_SCHEMA)

    @event.listens_for(engine.sync_engine, "connect")
    def set_oracle_current_schema(dbapi_connection, connection_record):
        try:
            cursor = dbapi_connection.cursor()
            cursor.execute(f"ALTER SESSION SET CURRENT_SCHEMA = {target_schema}")
            cursor.close()
        except Exception:
            pass

AsyncSessionLocal = async_sessionmaker(
    bind=engine,
    class_=AsyncSession,
    expire_on_commit=False,
    autocommit=False,
    autoflush=False
)


class Base(DeclarativeBase):
    pass


def get_tables_in_dependency_order():
    """Return mapped tables ordered by foreign keys, omitting cyclic edges."""
    return [
        table
        for table, _constraints in sort_tables_and_constraints(Base.metadata.tables.values())
        if table is not None
    ]


async def sync_oracle_identity_values(session: AsyncSession) -> None:
    """Advance Oracle identity generators after importing explicit primary keys."""
    if session.bind is None or session.bind.dialect.name != "oracle":
        return
    for table in get_tables_in_dependency_order():
        for column in table.columns:
            if column.identity is not None:
                await session.execute(text(
                    f"ALTER TABLE {table.name} MODIFY ({column.name} "
                    "GENERATED BY DEFAULT AS IDENTITY (START WITH LIMIT VALUE))"
                ))


async def get_db():
    """Async session dependency."""
    async with AsyncSessionLocal() as session:
        try:
            yield session
        finally:
            await session.close()
