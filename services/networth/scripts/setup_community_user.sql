-- ==============================================================================
-- Greenline Dedicated Database Tables & Scoped User Setup for Community Microservice
-- Run this script as the ADMIN schema owner in Oracle Autonomous Database
-- or as DBA / schema owner in local Oracle 23ai (FREEPDB1)
-- ==============================================================================
--
-- Deployment Instructions:
-- 1. Oracle Autonomous Database (Cloud):
--    Run as ADMIN user directly in SQL Worksheet, SQL Developer, or SQL*Plus.
--    The default tablespace is DATA and schema owner is ADMIN.
--
-- 2. Local Docker Container (Oracle Free 23ai / FREEPDB1):
--    Run as SYSTEM or schema owner. If running in the local docker container where
--    default permanent tablespace is USERS and schema owner is GREENLINE_TEST:
--    - Substitute DATA with USERS
--    - Substitute ADMIN. with GREENLINE_TEST.
-- ==============================================================================

-- 1. Create dedicated community tables in ADMIN schema
CREATE TABLE ADMIN.community_posts (
  id NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  user_id VARCHAR2(255) NOT NULL,
  author_pseudonym VARCHAR2(255),
  content CLOB NOT NULL,
  media_attachments CLOB,
  comments_count NUMBER DEFAULT 0 NOT NULL,
  created_at TIMESTAMP WITH TIME ZONE DEFAULT CURRENT_TIMESTAMP NOT NULL,
  updated_at TIMESTAMP WITH TIME ZONE DEFAULT CURRENT_TIMESTAMP NOT NULL
);

CREATE TABLE ADMIN.community_comments (
  id NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  post_id NUMBER NOT NULL,
  parent_comment_id NUMBER,
  user_id VARCHAR2(255) NOT NULL,
  author_pseudonym VARCHAR2(255),
  content CLOB NOT NULL,
  created_at TIMESTAMP WITH TIME ZONE DEFAULT CURRENT_TIMESTAMP NOT NULL,
  updated_at TIMESTAMP WITH TIME ZONE DEFAULT CURRENT_TIMESTAMP NOT NULL,
  CONSTRAINT fk_community_comments_post FOREIGN KEY (post_id) REFERENCES ADMIN.community_posts(id) ON DELETE CASCADE,
  CONSTRAINT fk_community_comments_parent FOREIGN KEY (parent_comment_id) REFERENCES ADMIN.community_comments(id) ON DELETE CASCADE
);

CREATE TABLE ADMIN.community_users (
  user_uuid VARCHAR2(36) PRIMARY KEY,
  auth0_sub VARCHAR2(255) NOT NULL UNIQUE,
  pseudonym VARCHAR2(255) NOT NULL,
  created_at TIMESTAMP WITH TIME ZONE DEFAULT CURRENT_TIMESTAMP NOT NULL,
  updated_at TIMESTAMP WITH TIME ZONE DEFAULT CURRENT_TIMESTAMP NOT NULL
);

-- 2. Create the dedicated Community microservice database user
-- In Oracle Autonomous Cloud DB: Passwords must be 12-30 characters, contain
-- uppercase, lowercase, numbers, and not include username.
CREATE USER GREENLINE_COMMUNITY IDENTIFIED BY "SecureCommunity2026#DbPass"
  DEFAULT TABLESPACE DATA
  TEMPORARY TABLESPACE TEMP
  QUOTA UNLIMITED ON DATA;

-- 3. Grant basic connection capability ONLY (Zero DDL privileges)
GRANT CREATE SESSION TO GREENLINE_COMMUNITY;

-- 4. Grant DML (SELECT, INSERT, UPDATE, DELETE) ONLY on dedicated Community tables
GRANT SELECT, INSERT, UPDATE, DELETE ON ADMIN.community_posts TO GREENLINE_COMMUNITY;
GRANT SELECT, INSERT, UPDATE, DELETE ON ADMIN.community_comments TO GREENLINE_COMMUNITY;
GRANT SELECT, INSERT, UPDATE, DELETE ON ADMIN.community_users TO GREENLINE_COMMUNITY;

-- 5. Excluded Tables (Explicitly NO grants):
-- Zero privileges on all 21 core financial tables (users, accounts, assets, transactions,
-- lots, lot_sales, price_history, dividends, expected_dividends, cash_flows,
-- cashflow_transactions, cashflow_payments, cashflow_items, categories, networth_snapshots,
-- networth_by_asset_class, xirr_cache, benchmarks, app_settings, api_keys, schema_migrations)
-- Community domain has zero access to user financials, credentials, or core ledgers.

-- 6. Attach AFTER LOGON trigger on GREENLINE_COMMUNITY schema to automatically resolve
-- table names against schema owner without requiring "ADMIN." prefixes in queries
CREATE OR REPLACE TRIGGER GREENLINE_COMMUNITY.set_current_schema
AFTER LOGON ON GREENLINE_COMMUNITY.SCHEMA
BEGIN
  EXECUTE IMMEDIATE 'ALTER SESSION SET CURRENT_SCHEMA = ADMIN';
END;
