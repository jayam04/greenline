-- Run as the Oracle database owner/ADMIN. Change the local development password
-- below for production and configure ORACLE_NETWORTH_HISTORY_PASSWORD to match.
-- This creates an isolated schema for
-- daily net-worth history while keeping financial source tables read-only.
CREATE USER GREENLINE_NW_HISTORY IDENTIFIED BY "LocalHistory2026#Db"
  DEFAULT TABLESPACE DATA
  TEMPORARY TABLESPACE TEMP
  QUOTA UNLIMITED ON DATA;
GRANT CREATE SESSION TO GREENLINE_NW_HISTORY;

GRANT SELECT ON ADMIN.users TO GREENLINE_NW_HISTORY;
GRANT SELECT ON ADMIN.accounts TO GREENLINE_NW_HISTORY;
GRANT SELECT ON ADMIN.assets TO GREENLINE_NW_HISTORY;
GRANT SELECT ON ADMIN.transactions TO GREENLINE_NW_HISTORY;
GRANT SELECT ON ADMIN.lots TO GREENLINE_NW_HISTORY;
GRANT SELECT ON ADMIN.lot_sales TO GREENLINE_NW_HISTORY;
GRANT SELECT ON ADMIN.price_history TO GREENLINE_NW_HISTORY;
GRANT SELECT ON ADMIN.dividends TO GREENLINE_NW_HISTORY;
GRANT SELECT ON ADMIN.cash_flows TO GREENLINE_NW_HISTORY;
GRANT SELECT ON ADMIN.cashflow_transactions TO GREENLINE_NW_HISTORY;
GRANT SELECT ON ADMIN.cashflow_payments TO GREENLINE_NW_HISTORY;
GRANT SELECT ON ADMIN.cashflow_items TO GREENLINE_NW_HISTORY;
GRANT SELECT ON ADMIN.categories TO GREENLINE_NW_HISTORY;
GRANT SELECT ON ADMIN.networth_snapshots TO GREENLINE_NW_HISTORY;

CREATE TABLE GREENLINE_NW_HISTORY.networth_snapshots (
  snapshot_id NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  user_id NUMBER NOT NULL,
  snapshot_date DATE NOT NULL,
  total_invested FLOAT NOT NULL,
  total_current_value FLOAT NOT NULL,
  cash_balance FLOAT NOT NULL,
  total_realized_pnl FLOAT NOT NULL,
  total_unrealized_pnl FLOAT NOT NULL,
  net_worth FLOAT NOT NULL,
  CONSTRAINT uix_nwh_user_date UNIQUE (user_id, snapshot_date)
);
CREATE INDEX GREENLINE_NW_HISTORY.idx_nwh_snapshot_user_date
  ON GREENLINE_NW_HISTORY.networth_snapshots (user_id, snapshot_date);

CREATE TABLE GREENLINE_NW_HISTORY.networth_by_asset_class (
  id NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  user_id NUMBER NOT NULL,
  snapshot_id NUMBER NOT NULL,
  asset_class VARCHAR2(255) NOT NULL,
  value FLOAT NOT NULL,
  CONSTRAINT fk_nwh_asset_snapshot FOREIGN KEY (snapshot_id)
    REFERENCES GREENLINE_NW_HISTORY.networth_snapshots(snapshot_id) ON DELETE CASCADE
);
CREATE INDEX GREENLINE_NW_HISTORY.idx_nwh_asset_snapshot
  ON GREENLINE_NW_HISTORY.networth_by_asset_class (snapshot_id);
